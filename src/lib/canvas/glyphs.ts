/** A bitmap: rows of characters, where '.' is off and any other character is a colour key. */
export type Bitmap = readonly string[];

/** Parses "key rows key rows ..." with rows joined by '/', the compact form the glyph tables are written in. */
export function parseGlyphs(spec: string): Record<string, Bitmap> {
  const parts = spec.trim().split(/\s+/);
  const out: Record<string, Bitmap> = {};
  for (let i = 0; i + 1 < parts.length; i += 2) out[parts[i] as string] = (parts[i + 1] as string).split('/');
  return out;
}

